from __future__ import annotations

import csv
import json
from pathlib import Path

from findings.digest import manifest_sha256


def write_evidence(ledger: dict, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    _write_findings_csv(out / "findings.csv", ledger["findings"])
    _write_poam(out / "poam.csv", ledger["findings"])
    _write_overdue(out / "overdue.csv", ledger["findings"])
    controls = ledger.get("controls")
    if controls is None:
        from findings.ledger import build_controls

        controls = build_controls(ledger["findings"])
    _write_controls_csv(out / "controls.csv", controls)
    (out / "controls.md").write_text(_controls_md(controls), encoding="utf-8")
    (out / "brief.md").write_text(_brief_md(ledger), encoding="utf-8")
    (out / "drift.md").write_text(_drift_md(ledger), encoding="utf-8")
    (out / "exceptions.md").write_text(_exceptions_md(ledger), encoding="utf-8")
    (out / "handoff.md").write_text(_handoff_md(ledger), encoding="utf-8")
    backups = ledger.get("backups") or []
    _write_backups_csv(out / "backups.csv", backups)
    (out / "backups.md").write_text(_backups_md(ledger, backups), encoding="utf-8")
    (out / "attestation.json").write_text(
        json.dumps(
            {
                "tool": ledger["tool"],
                "version": ledger["version"],
                "as_of": ledger["generated_for"],
                "site": ledger["site"].get("name"),
                "statement": (
                    "Produced offline from scanner exports and backup records. "
                    "This register did not scan a host and did not change one."
                ),
                "sources": ledger["sources"],
                "manifest_sha256": manifest_sha256(ledger["sources"]),
                "manifest_format": (
                    "sha256 of the sorted lines '<sha256>  <file>', one per distinct source file, "
                    "each ending in a newline. Null when any source has no recorded hash."
                ),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    host_dir = out / "by-host"
    host_dir.mkdir(exist_ok=True)
    by_host: dict[str, list] = {}
    for finding in ledger["findings"]:
        by_host.setdefault(finding["host"], []).append(finding)
    for host, findings in by_host.items():
        lines = [f"# {host}", ""]
        for finding in findings:
            if finding["clock"] == "closed":
                continue
            lines.append(f"## {finding['control']} — CAT {finding['cat']} — {finding['clock']}")
            lines.append("")
            lines.append(finding["title"])
            lines.append("")
            lines.append(f"Due: {finding['due'] or 'n/a'}. Class: {finding['remediation']['class']}.")
            lines.append("")
            lines.append(finding["remediation"]["why"])
            lines.append("")
        (host_dir / f"{host.split('.')[0]}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_remediation_plan(ledger: dict, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by the findings register. Read it before you run anything.",
        "# Tags under `automate` are the only ones the sample playbook should get on an unattended run.",
        "windows:",
    ]
    for window in ledger["windows"]:
        auto = [item["control"] for item in window["items"] if item["class"] == "automate"]
        held = [f"{item['control']} ({item['class']})" for item in window["items"] if item["class"] != "automate"]
        lines.append(f"  - host: {window['host']}")
        lines.append(f"    note: {json.dumps(window['note'])}")
        lines.append("    automate_controls:")
        if auto:
            for control in auto:
                lines.append(f"      - {control}")
        else:
            lines.append("      []")
        lines.append("    hold:")
        if held:
            for control in held:
                lines.append(f"      - {json.dumps(control)}")
        else:
            lines.append("      []")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_findings_csv(path: Path, findings: list[dict]) -> None:
    fields = [
        "host",
        "control",
        "vuln_num",
        "rule_id",
        "cve",
        "title",
        "cat",
        "clock",
        "first_seen",
        "last_seen",
        "due",
        "days_overdue",
        "remediation_class",
        "cci",
        "flags",
    ]
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for finding in findings:
            writer.writerow(
                {
                    "host": finding["host"],
                    "control": finding["control"],
                    "vuln_num": finding.get("vuln_num") or "",
                    "rule_id": finding.get("rule_id") or "",
                    "cve": finding.get("cve") or "",
                    "title": finding["title"],
                    "cat": finding["cat"],
                    "clock": finding["clock"],
                    "first_seen": finding["first_seen"],
                    "last_seen": finding["last_seen"],
                    "due": finding["due"] or "",
                    "days_overdue": finding["days_overdue"],
                    "remediation_class": finding["remediation"]["class"],
                    "cci": " ".join(finding["cci"]),
                    "flags": " ".join(finding["flags"]),
                }
            )


def _write_poam(path: Path, findings: list[dict]) -> None:
    fields = [
        "POA&M ID",
        "Weakness",
        "Asset",
        "Control",
        "CAT",
        "Source",
        "Original detection",
        "Scheduled completion",
        "Status",
        "Milestone",
        "CCI",
        "NIST",
        "Comments",
    ]
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        number = 1
        for finding in findings:
            if finding["clock"] == "closed":
                continue
            if finding["clock"] == "excepted":
                status = "Risk accepted"
                milestone = "Revisit on the exception end date."
            elif finding["clock"] == "overdue":
                status = "Ongoing, past due"
                milestone = finding["remediation"]["summary"]
            else:
                status = "Ongoing"
                milestone = finding["remediation"]["summary"]
            writer.writerow(
                {
                    "POA&M ID": f"POAM-{number:03d}",
                    "Weakness": finding["title"],
                    "Asset": finding["host"],
                    "Control": finding["control"],
                    "CAT": finding["cat"],
                    "Source": ",".join(finding["history"][-1]["sources"]),
                    "Original detection": finding["first_seen"],
                    "Scheduled completion": finding["due"] or "",
                    "Status": status,
                    "Milestone": milestone,
                    "CCI": " ".join(finding["cci"]),
                    "NIST": " ".join(finding["nist"]),
                    "Comments": finding["comments"] or finding["detail"],
                }
            )
            number += 1


def _write_overdue(path: Path, findings: list[dict]) -> None:
    _write_findings_csv(path, [item for item in findings if item["clock"] == "overdue"])


CONTROL_FIELDS = [
    "control",
    "family",
    "ccis",
    "worst_clock",
    "open",
    "overdue",
    "due_soon",
    "excepted",
    "closed",
    "open_all_excepted",
    "earliest_due",
    "findings",
]


def _write_controls_csv(path: Path, controls: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=CONTROL_FIELDS)
        writer.writeheader()
        for row in controls:
            writer.writerow(
                {
                    **{name: row[name] for name in CONTROL_FIELDS},
                    "ccis": " ".join(row["ccis"]),
                    "open_all_excepted": "yes" if row["open_all_excepted"] else "no",
                    "earliest_due": row["earliest_due"] or "",
                    "findings": ";".join(item["slug"] for item in row["findings"]),
                }
            )


def _controls_md(controls: list[dict]) -> str:
    lines = [
        "# Controls",
        "",
        "The NIST SP 800-53 controls behind the CCIs the scanners reported. "
        "A finding with no CCI, or with a CCI no scanner tied to a control, is listed under unmapped.",
        "",
    ]
    family = None
    for row in controls:
        if row["family"] != family:
            family = row["family"]
            members = [item for item in controls if item["family"] == family]
            open_count = sum(item["open"] for item in members)
            overdue = sum(item["overdue"] for item in members)
            lines.append(f"## {family}")
            lines.append("")
            noun = "control" if len(members) == 1 else "controls"
            lines.append(f"{len(members)} {noun}. {open_count} open, {overdue} overdue.")
            lines.append("")
        ccis = ", ".join(row["ccis"]) or "no CCI"
        lines.append(f"### {row['control']} — {row['worst_clock']}")
        lines.append("")
        summary = (
            f"{ccis}. {row['open']} open, {row['overdue']} overdue, {row['due_soon']} due soon, "
            f"{row['excepted']} excepted, {row['closed']} closed."
        )
        if row["earliest_due"]:
            summary += f" Earliest due {row['earliest_due']}."
        if row["open_all_excepted"]:
            summary += " Every open finding is under an approved exception."
        lines.append(summary)
        lines.append("")
        for item in row["findings"]:
            due = f", due {item['due']}" if item["due"] and item["clock"] != "closed" else ""
            lines.append(f"- {item['control']} on {item['host']} — CAT {item['cat']} — {item['clock']}{due}")
        lines.append("")
    if not controls:
        lines.append("No findings.")
        lines.append("")
    return "\n".join(lines)


def _brief_md(ledger: dict) -> str:
    lines = [f"# ISSO brief — {ledger['site'].get('name', 'site')}", ""]
    for paragraph in ledger["brief"]["paragraphs"]:
        lines.append(paragraph)
        lines.append("")
    return "\n".join(lines)


def _drift_md(ledger: dict) -> str:
    lines = ["# Drift", ""]
    for name in ("regressed", "new", "closed", "persistent", "opened_since_baseline"):
        rows = ledger["drift"][name]
        lines.append(f"## {name.replace('_', ' ')} ({len(rows)})")
        lines.append("")
        if not rows:
            lines.append("None.")
            lines.append("")
            continue
        for row in rows:
            lines.append(f"- {row['control']} on {row['host']} — {row['title']}")
        lines.append("")
    return "\n".join(lines)


def _exceptions_md(ledger: dict) -> str:
    lines = ["# Exceptions", ""]
    for item in ledger["exceptions"]:
        lines.append(f"## {item['id']} — {item['display_status']} — {item['control']}")
        lines.append("")
        lines.append(item.get("rationale", ""))
        lines.append("")
        lines.append(f"Compensating control: {item.get('compensating', '')}")
        lines.append("")
        lines.append(f"Approver: {item.get('approver_name', '')} ({item.get('approver', '')}). Expires {item.get('expires', '')}.")
        lines.append("")
    return "\n".join(lines)


def _handoff_md(ledger: dict) -> str:
    ready = "ready" if ledger["handoff"]["ready"] else "not ready"
    lines = [f"# Steady-state handoff — {ready}", ""]
    for gate in ledger["handoff"]["gates"]:
        lines.append(f"- **{gate['status'].upper()}** {gate['title']}. {gate['detail']}")
    lines.append("")
    return "\n".join(lines)


BACKUP_FIELDS = [
    "host",
    "method",
    "status",
    "rpo_hours",
    "rpo_met",
    "last_success",
    "last_success_age_hours",
    "restore_test_max_days",
    "restore_met",
    "qualifying_test_date",
    "qualifying_test_age_days",
    "qualifying_test_scope",
    "qualifying_test_result",
    "qualifying_test_duration_minutes",
    "newest_test_date",
    "newest_test_scope",
    "newest_test_result",
    "newest_test_duration_minutes",
    "rto_hours",
    "rto_met",
    "restore_scope_ok",
    "newest_test_restored",
    "flags",
    "reasons",
]


def _yes_no(value) -> str:
    if value is None:
        return "unknown"
    return "yes" if value else "no"


def _blank(value) -> object:
    return "" if value is None else value


def _write_backups_csv(path: Path, backups: list[dict]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=BACKUP_FIELDS)
        writer.writeheader()
        for row in backups:
            qualifying = row.get("qualifying_test") or {}
            newest = row.get("newest_test") or {}
            # A record with no entries still carries a date; it is reported, with scope unknown.
            qualifying_date = qualifying.get("date") or ("" if row.get("restore_tests") else row.get("last_restore_test") or "")
            writer.writerow(
                {
                    "host": row["host"],
                    "method": row["method"],
                    "status": row["status"],
                    "rpo_hours": row["rpo_hours"],
                    "rpo_met": _yes_no(row["rpo_met"]),
                    "last_success": row["last_success"],
                    "last_success_age_hours": row["age_hours"],
                    "restore_test_max_days": row["restore_test_max_days"],
                    "restore_met": _yes_no(row["restore_met"]),
                    "qualifying_test_date": qualifying_date,
                    "qualifying_test_age_days": _blank(row.get("restore_age_days")),
                    "qualifying_test_scope": qualifying.get("scope", ""),
                    "qualifying_test_result": qualifying.get("result", ""),
                    "qualifying_test_duration_minutes": _blank(qualifying.get("duration_minutes")),
                    "newest_test_date": newest.get("date", ""),
                    "newest_test_scope": newest.get("scope", ""),
                    "newest_test_result": newest.get("result", ""),
                    "newest_test_duration_minutes": _blank(newest.get("duration_minutes")),
                    "rto_hours": _blank(row.get("rto_hours")),
                    "rto_met": _yes_no(row.get("rto_met")),
                    "restore_scope_ok": _yes_no(row.get("restore_scope_ok")),
                    "newest_test_restored": newest.get("restored", ""),
                    "flags": " ".join(row.get("flags") or []),
                    "reasons": " ".join(row["reasons"]),
                }
            )


def _backups_md(ledger: dict, backups: list[dict]) -> str:
    lines = [
        "# Backups",
        "",
        f"As of {ledger.get('generated_for', '')}. RPO is measured to noon on that day. "
        "A restore test counts only when it was a full restore that passed. A config-only or partial restore, "
        "or a failed one, is listed but does not reset the restore-test clock. RTO is checked against the newest test's duration.",
        "",
    ]
    if not backups:
        lines.append("No backup records.")
        lines.append("")
        return "\n".join(lines)
    lines.append(
        "| Host | Method | RPO | Last good | Newest qualifying restore test | Scope | Duration vs RTO | Result | Status |"
    )
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for row in backups:
        qualifying = row.get("qualifying_test")
        rpo = f"{row['rpo_hours']}h, {'met' if row['rpo_met'] else 'missed'}"
        if qualifying:
            test = f"{qualifying['date']} ({row['restore_age_days']} days ago)"
        elif row.get("restore_tests"):
            test = "none qualifies"
        elif row.get("last_restore_test"):
            test = f"{row['last_restore_test']} ({row['restore_age_days']} days ago, scope not recorded)"
        else:
            test = "none on record"
        scope = qualifying["scope"] if qualifying else ""
        result = qualifying["result"] if qualifying else ""
        lines.append(
            f"| {row['host']} | {row['method']} | {rpo} | {row['age_hours']} h ago | {test} | {scope} | "
            f"{_rto_cell(qualifying, row.get('rto_hours'))} | {result} | {row['status']} |"
        )
    lines.append("")
    for row in backups:
        lines.append(f"## {row['host']} — {row['status']}")
        lines.append("")
        if row["reasons"]:
            for reason in row["reasons"]:
                lines.append(f"- {reason}")
        else:
            lines.append("- RPO, RTO, and the restore-test window are inside policy.")
        for flag in row.get("flags") or []:
            if flag == "restore_date_mismatch":
                lines.append(
                    "- Flag: restore_date_mismatch. last_restore_test does not match the newest restore test entry. The entries were used."
                )
            else:
                lines.append(f"- Flag: {flag}.")
        lines.append("")
        tests = row.get("restore_tests") or []
        if tests:
            lines.append("| Date | Scope | Duration vs RTO | Result | Counts | Restored | Tester | Ticket |")
            lines.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
            for test in tests:
                lines.append(
                    f"| {test['date']} | {test['scope']} | {_rto_cell(test, row.get('rto_hours'))} | {test['result']} | "
                    f"{'yes' if test['qualifies'] else 'no'} | {test['restored']} | {test['tester']} | {test.get('ticket') or ''} |"
                )
            lines.append("")
        if row.get("notes"):
            lines.append(row["notes"])
            lines.append("")
    return "\n".join(lines)


def _rto_cell(test: dict | None, rto_hours) -> str:
    if not test:
        return ""
    duration = test.get("duration_minutes")
    if duration is None:
        return f"not recorded / {rto_hours}h"
    if test.get("rto_met") is None:
        return f"{duration} min, no RTO"
    return f"{duration} min / {rto_hours}h, {'met' if test['rto_met'] else 'missed'}"
